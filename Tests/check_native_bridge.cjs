const {readFileSync} = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = readFileSync('Pocket/NativeBridge.swift', 'utf8').split('#"""')[1].split('"""#')[0];
(async () => {
  const calls = [];
  const window = {webkit: {messageHandlers: {pocketNative: {postMessage: async body => {calls.push(body); return {ok: true};}}}}};
  window.top = window;
  vm.runInNewContext(source, {window});
  assert.equal(window.pocketNative.version, 1);
  assert.ok(Object.isFrozen(window.pocketNative));
  await window.pocketNative.capabilities();
  await window.pocketNative.haptics.tap();
  await window.pocketNative.motion.sample();
  await window.pocketNative.pedometer.today();
  await window.pocketNative.location.start();
  await window.pocketNative.location.read();
  await window.pocketNative.location.stop();
  await window.pocketNative.widgets.clear();
  assert.deepEqual(JSON.parse(JSON.stringify(calls)), ['capabilities','haptics.tap','motion.sample','pedometer.today','location.start','location.read','location.stop','widgets.clear'].map(method => ({version:1, method})));
  await window.pocketNative.widgets.update({title: 'Focus', body: '20 minutes'});
  assert.deepEqual(JSON.parse(JSON.stringify(calls.at(-1))), {version: 1, method: 'widgets.update', params: {title: 'Focus', body: '20 minutes'}});
  window.webkit.messageHandlers.pocketNative.postMessage = async () => {throw Error('permission_denied');};
  await assert.rejects(window.pocketNative.motion.sample(), /permission_denied/);
  const frame = {top: {}};
  vm.runInNewContext(source, {window: frame});
  assert.equal(frame.pocketNative, undefined);
  console.log('Native bridge API, promise errors, and iframe injection checks passed');
})().catch(error => {console.error(error); process.exitCode = 1;});
